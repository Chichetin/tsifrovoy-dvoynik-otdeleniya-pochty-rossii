/**
 * Подпись длины стены вдоль самой стены.
 *
 * Проектировщик перепланировки читает план, чтобы понять, влезет ли ряд
 * стеллажей вдоль стены, и до сих пор узнать длину можно было только выделив
 * перегородку и посмотрев карточку. Настоящая длина берётся из геометрии
 * (`wallLength`), а не из отдельно хранимого числа: подпись не может разойтись
 * с планом.
 *
 * Порог у подписи один и он не подобран на глаз: подпись показывается тогда,
 * когда она целиком помещается между концами стены на экране. Подпись длиннее
 * своей стены налезает на соседние и врёт о том, что измеряет; подпись короче
 * стены читается однозначно. Отсюда и число `WALL_LABEL_CHAR_PX` — ширина
 * знака строки вида «12,50 м» в шрифте подписи, измеренная в браузере через
 * `canvas.measureText` (`docs/verification/measure/`).
 *
 * Модуль чистый: ни React, ни Konva, ни состояния — только числа, которые
 * проверяются тестом.
 */

import type { Point, Viewport, Wall } from '../../contracts/model';
import { modelToScreen, wallLength } from '../../domain/geometry';
import { formatLength } from '../../domain/number-format';

/** Мельче названия зоны (13 px): длина стены — справочное число, а не заголовок. */
export const WALL_LABEL_FONT_PX = 11;

/**
 * Ширина знака при `WALL_LABEL_FONT_PX`. Строка подписи — это цифры, запятая,
 * неразрывный пробел и «м», и их ширины близки, поэтому оценка по среднему
 * знаку точна до пикселя на всей строке.
 *
 * Измерено в браузере, а не подобрано: `canvas.measureText` для шрифта Konva
 * по умолчанию (11 px Arial) даёт 5,34 px на знак для «4,20 м» и 5,45 px для
 * «12,50 м» (`docs/verification/measure/char-width.json`). Взято 6,0 — с
 * запасом на подстановку шрифта там, где Arial нет: ошибка в большую сторону
 * прячет подпись у самой короткой стены, ошибка в меньшую выпускает её за
 * концы стены, а это как раз то, ради чего порог и заводился.
 */
export const WALL_LABEL_CHAR_PX = 6;

/** Отступ от каждого конца стены, чтобы подпись не упиралась в угол. */
export const WALL_LABEL_END_MARGIN_PX = 8;

/** Зазор между гранью стены и подписью: подпись лежит рядом со стеной, не на ней. */
export const WALL_LABEL_GAP_PX = 4;

export type WallLengthLabel = {
  /** «4,20 м» — с запятой и неразрывным пробелом, как везде в интерфейсе. */
  text: string;
  /** Центр подписи на экране: середина стены, сдвинутая с неё вбок. */
  x: number;
  y: number;
  /** Поворот в градусах экрана; подпись никогда не читается вверх ногами. */
  rotation: number;
  /** Оценка ширины подписи — то самое число, по которому решалось, влезает ли она. */
  width: number;
};

/** Оценка ширины строки подписи в пикселях. */
export function wallLabelWidthPx(text: string): number {
  return text.length * WALL_LABEL_CHAR_PX;
}

/**
 * Подпись для стены или `null`, если она не влезает между концами стены.
 *
 * Подпись лежит не на стене, а рядом с ней — на полу: стена нарисована тёмной
 * заливкой толщиной в несколько пикселей, и текст поверх неё наполовину
 * оказывается на полу и наполовину на стене, то есть не читается ни там, ни
 * там.
 *
 * Сторону выбирает `away` — точка, от которой подпись уходит; приложение даёт
 * середину помещения, и наружные стены получают подписи снаружи, как на
 * архитектурном чертеже, а не поверх зон и оборудования. Стена, проходящая
 * ровно через эту точку, и вызов без неё откатываются на одно правило для
 * всех: сторона, которая на экране выше. Правило должно быть именно таким,
 * одинаковым для стены и для её же обратного направления, иначе подписи
 * прыгали бы со стороны на сторону от того, в какую сторону стену рисовали.
 *
 * Повороты держатся в пределах ±90°: стена, идущая справа налево, получает ту
 * же подпись, перевёрнутую на 180°, иначе текст читался бы зеркально.
 */
export function wallLengthLabel(
  wall: Wall,
  viewport: Viewport,
  away?: Point,
): WallLengthLabel | null {
  const length_m = wallLength(wall);
  if (length_m <= 0) return null;

  const text = formatLength(length_m);
  const width = wallLabelWidthPx(text);

  const [x1, y1] = modelToScreen(wall.from, viewport);
  const [x2, y2] = modelToScreen(wall.to, viewport);
  const onScreen = Math.hypot(x2 - x1, y2 - y1);
  if (onScreen < width + WALL_LABEL_END_MARGIN_PX * 2) return null;

  let rotation = (Math.atan2(y2 - y1, x2 - x1) * 180) / Math.PI;
  if (rotation > 90) rotation -= 180;
  if (rotation < -90) rotation += 180;

  // Нормаль к стене в экранных координатах.
  let nx = -(y2 - y1) / onScreen;
  let ny = (x2 - x1) / onScreen;
  const midX = (x1 + x2) / 2;
  const midY = (y1 + y2) / 2;
  let side = 0;
  if (away !== undefined) {
    const [ax, ay] = modelToScreen(away, viewport);
    side = nx * (ax - midX) + ny * (ay - midY);
  }
  // Больше нуля — нормаль смотрит на `away`, значит подпись идёт в другую
  // сторону; ровно ноль (стена проходит через точку или её не дали) —
  // запасное правило: вверх экрана, а для стены, вертикальной на экране, —
  // влево. Второе условие обязательно: у вертикальной стены `ny` равен нулю, и
  // без него сторона зависела бы от того, снизу вверх или сверху вниз её
  // нарисовали.
  if (side > 0 || (side === 0 && (ny > 0 || (ny === 0 && nx > 0)))) {
    nx = -nx;
    ny = -ny;
  }
  const offset = (wall.thickness_m * viewport.scale) / 2 + WALL_LABEL_GAP_PX + WALL_LABEL_FONT_PX / 2;

  return {
    text,
    x: midX + nx * offset,
    y: midY + ny * offset,
    rotation,
    width,
  };
}
